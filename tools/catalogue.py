#!/usr/bin/env python3
"""Tools for catalogue/apps.toml.
  tools/catalogue.py check              every `pacman` name must exist in core/extra/multilib, every `aur` name in the AUR (needs network for the AUR)
  tools/catalogue.py netinstall FILE    the installer's checkbox list (Calamares netinstall YAML); one group per catalogue group, one item per app
  tools/catalogue.py meta DIR           one meta-package source per app: DIR/sunshine-app-<id>/PKGBUILD (+ .install, + <id>.json); installing it installs the
                                        official packages and queues the AUR/setup/web-app part for `sunshine-apps`
usage: python3 tools/catalogue.py check|netinstall|meta ..."""
import json, subprocess, sys, tomllib, urllib.request, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
apps = tomllib.loads((root / "catalogue/apps.toml").read_text())["app"]

def official():
    names = set()
    for repo in ("core", "extra", "multilib"):
        out = subprocess.run(["pacman", "-Sl", repo], capture_output=True, text=True).stdout
        names |= {l.split()[1] for l in out.splitlines() if len(l.split()) > 1}
    return names

def aur(names):
    found = set()
    names = sorted(names)
    for i in range(0, len(names), 100):
        url = "https://aur.archlinux.org/rpc/v5/info?" + "&".join("arg[]=" + n for n in names[i:i + 100])
        with urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "sunshineos-catalogue-check"}), timeout=30) as r:
            found |= {x["Name"] for x in json.load(r)["results"]}
    return found

def check():
    ids = [a["id"] for a in apps]
    bad = False
    dup = {i for i in ids if ids.count(i) > 1}
    if dup: print("duplicate ids:", ", ".join(sorted(dup))); bad = True
    for a in apps:
        for k in ("id", "name", "group", "desc"):
            if k not in a: print(f"{a.get('id','?')}: missing '{k}'"); bad = True
        if not any(k in a for k in ("pacman", "aur", "webapp", "setup")): print(f"{a['id']}: installs nothing"); bad = True
    off = official(); want = {p for a in apps for p in a.get("pacman", [])}
    missing = sorted(want - off)
    print(f"official packages: {len(want)} wanted, {len(missing)} not found in core/extra/multilib")
    for m in missing: print("   not official:", m, "(used by:", ", ".join(a["id"] for a in apps if m in a.get("pacman", [])) + ")")
    wa = {p for a in apps for p in a.get("aur", [])}
    try:
        have = aur(wa); amiss = sorted(wa - have)
        print(f"AUR packages: {len(wa)} wanted, {len(amiss)} not found in the AUR")
        for m in amiss: print("   not in the AUR:", m, "(used by:", ", ".join(a["id"] for a in apps if m in a.get("aur", [])) + ")")
        bad |= bool(amiss)
    except Exception as e:
        print("AUR check skipped (no network?):", e)
    return 1 if (bad or missing) else 0

GROUP_TEXT = {
    "Everyday": "Browser, office, viewers",
    "Internet": "Browsers, chat, remote access, web apps",
    "Media and games": "Players, game launchers, Windows compatibility",
    "Development": "Editors, IDEs, databases, Git tools, terminals",
    "System": "Kernels, virtual machines, printing, extra repositories",
    "Notes and AI": "Notes, Claude, launchers and package manager",
}
ORDER = list(GROUP_TEXT)

def q(s): return json.dumps(s, ensure_ascii=False)

def netinstall(path):
    out = ["# Generated by tools/catalogue.py netinstall from catalogue/apps.toml: do not edit by hand."]
    for g in ORDER:
        items = [a for a in apps if a["group"] == g]
        if not items: continue
        out += [f"- name: {q(g)}", f"  description: {q(GROUP_TEXT[g])}", "  hidden: false", "  selected: false", "  critical: false", "  expanded: false", "  subgroups:"]
        for a in items:
            where = [k for k, v in (("official repos", a.get("pacman")), ("AUR, after the first online start", a.get("aur")), ("web app", a.get("webapp"))) if v]
            out += [f"    - name: {q(a['name'])}", f"      description: {q(a['desc'] + ' (' + ', '.join(where) + ')' if where else a['desc'])}",
                    f"      selected: {'true' if a.get('selected') else 'false'}", "      packages:", f"        - sunshine-app-{a['id']}"]
    pathlib.Path(path).write_text("\n".join(out) + "\n")
    print(f"{path}: {len([a for a in apps])} apps in {len(ORDER)} groups")

def meta(dest):
    import datetime
    ver = (datetime.date.today() - datetime.date(2026, 1, 1)).days
    dest = pathlib.Path(dest)
    for a in apps:
        name = f"sunshine-app-{a['id']}"; d = dest / name; d.mkdir(parents=True, exist_ok=True)
        info = {k: a[k] for k in ("id", "name", "aur", "webapp", "setup") if k in a}
        (d / f"{a['id']}.json").write_text(json.dumps(info, ensure_ascii=False, indent=1) + "\n")
        queued = any(k in a for k in ("aur", "webapp", "setup"))
        deps = " ".join(f"'{p}'" for p in a.get("pacman", []) + ["sunshine-base"])
        pk = [f"# Generated by tools/catalogue.py meta from catalogue/apps.toml: do not edit by hand.", "# Maintainer: tak0dan", f"pkgname={name}", f"pkgver={ver}", "pkgrel=1",
              f"pkgdesc={q(a['name'] + ': ' + a['desc'])}".replace('"', "'", 0), "arch=('any')", "license=('MIT')", f"depends=({deps})"]
        if queued: pk.append(f"install={name}.install")
        pk += [f"source=({a['id']}.json)", "sha256sums=('SKIP')", "", "package() {", f"  install -Dm644 {a['id']}.json \"$pkgdir/usr/share/sunshine/apps.d/{a['id']}.json\"", "}"]
        (d / "PKGBUILD").write_text("\n".join(pk) + "\n")
        inst = d / f"{name}.install"
        if queued: inst.write_text(f"post_install() {{\n  mkdir -p /var/lib/sunshine/pending\n  : > /var/lib/sunshine/pending/{a['id']}\n}}\n")
        elif inst.exists(): inst.unlink()
    print(f"{len(apps)} meta-package sources in {dest}")

if __name__ == "__main__":
    c = sys.argv[1] if len(sys.argv) > 1 else ""
    if c == "check": sys.exit(check())
    elif c == "netinstall" and len(sys.argv) > 2: netinstall(sys.argv[2])
    elif c == "meta" and len(sys.argv) > 2: meta(sys.argv[2])
    else: print(__doc__); sys.exit(2)
