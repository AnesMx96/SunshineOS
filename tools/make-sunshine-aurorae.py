#!/usr/bin/env python3
"""Window decoration of the Sunshine theme (Aurorae): keeps the frame geometry of overlay/system/.../aurorae/themes/Sunshine, makes the title bar solid in the
window colour, writes Windows 11 style buttons (minimize, maximize, restore, close, all desktops, keep above/below) in the Sunshine palette and the text colours.
usage: python3 tools/make-sunshine-aurorae.py     (edits overlay/system/usr/share/aurorae/themes/Sunshine and mirrors it into profile/airootfs)"""
import pathlib, re, shutil, os
root = pathlib.Path(__file__).resolve().parent.parent
T = root / "overlay/system/usr/share/aurorae/themes/Sunshine"
P = root / "profile/airootfs/usr/share/aurorae/themes/Sunshine"
BG_ACTIVE, BG_INACTIVE = "#0e1422", "#11172a"       # = the window colour of the Sunshine colour scheme
TEXT, MUTED = "#efe5d0", "#9a927f"
CLOSE_HOVER, CLOSE_PRESSED = "#e06c75", "#c25a62"
W, H = 44, 28

def glyph(kind, color):
    cx, cy = W / 2, H / 2
    s = f'stroke="{color}" stroke-width="1" fill="none" stroke-linecap="round" stroke-linejoin="round"'
    return {
        "minimize": f'<path d="M{cx-5},{cy+.5} H{cx+5}" {s}/>',
        "maximize": f'<rect x="{cx-4.5}" y="{cy-4.5}" width="9" height="9" rx="1.5" {s}/>',
        "restore": f'<rect x="{cx-4.5}" y="{cy-2.5}" width="7" height="7" rx="1.5" {s}/><path d="M{cx-2.5},{cy-2.5} V{cy-4.5} a1.5,1.5 0 0 1 1.5,-1.5 H{cx+3} a1.5,1.5 0 0 1 1.5,1.5 V{cy+2} a1.5,1.5 0 0 1 -1.5,1.5 H{cx+2.5}" {s}/>',
        "close": f'<path d="M{cx-4.5},{cy-4.5} L{cx+4.5},{cy+4.5} M{cx+4.5},{cy-4.5} L{cx-4.5},{cy+4.5}" {s}/>',
        "alldesktops": f'<rect x="{cx-4}" y="{cy-4}" width="3" height="3" rx=".6" {s}/><rect x="{cx+1}" y="{cy-4}" width="3" height="3" rx=".6" {s}/><rect x="{cx-4}" y="{cy+1}" width="3" height="3" rx=".6" {s}/><rect x="{cx+1}" y="{cy+1}" width="3" height="3" rx=".6" {s}/>',
        "keepabove": f'<path d="M{cx-4},{cy+1.5} L{cx},{cy-2.5} L{cx+4},{cy+1.5} M{cx-4},{cy+4.5} H{cx+4}" {s}/>',
        "keepbelow": f'<path d="M{cx-4},{cy-1.5} L{cx},{cy+2.5} L{cx+4},{cy-1.5} M{cx-4},{cy-4.5} H{cx+4}" {s}/>',
    }[kind]

def button(kind):
    close = kind == "close"
    st = {   # state: (background colour, background opacity, glyph colour)
        "active": (None, 0, TEXT), "inactive": (None, 0, MUTED), "deactivated": (None, 0, MUTED),
        "hover": (CLOSE_HOVER if close else TEXT, 1 if close else .10, BG_ACTIVE if close else TEXT),
        "pressed": (CLOSE_PRESSED if close else TEXT, 1 if close else .16, BG_ACTIVE if close else TEXT),
    }
    out = [f'<?xml version="1.0" encoding="UTF-8"?>\n<!-- Sunshine theme button "{kind}". Generated by tools/make-sunshine-aurorae.py -->\n<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H*5}" viewBox="0 0 {W} {H*5}">']
    for i, (name, (bg, bo, fg)) in enumerate(st.items()):
        op = ' opacity=".4"' if name == "deactivated" else ""
        # every state has the same full-size rectangle (invisible when there is no background): Aurorae scales an element by its bounding box
        back = f'<rect x="0" y="0" width="{W}" height="{H}" fill="{bg or "#000000"}" fill-opacity="{bo if bg else 0}"/>'
        out.append(f'<g id="{name}-center" transform="translate(0,{i*H})"{op}>{back}{glyph(kind, fg)}</g>')
    out.append("</svg>\n")
    return "\n".join(out)

def main():
    for k in ("minimize", "maximize", "restore", "close", "alldesktops", "keepabove", "keepbelow"):
        (T / f"{k}.svg").write_text(button(k))
    d = (T / "decoration.svg").read_text()
    d = d.replace("opacity:0.65;fill:#141a2a", "opacity:1;fill:#0e1422")      # solid title bar and frame in the window colour
    (T / "decoration.svg").write_text(d)
    rc = (T / "Sunshinerc").read_text()
    rc = re.sub(r"ActiveTextColor=.*", "ActiveTextColor=239,229,208,255", rc)
    rc = re.sub(r"InactiveTextColor=.*", "InactiveTextColor=154,146,127,255", rc)
    (T / "Sunshinerc").write_text(rc)
    for r, ds, fs in os.walk(T):
        os.chmod(r, 0o755)
        for f in fs: os.chmod(os.path.join(r, f), 0o644)
    if P.exists(): shutil.rmtree(P)
    shutil.copytree(T, P)
    print("aurorae theme updated:", T)

if __name__ == "__main__":
    main()
